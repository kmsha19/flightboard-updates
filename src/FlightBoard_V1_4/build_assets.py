#!/usr/bin/env python3
"""Generate offline logos and browser assets from pinned local sources.

24x16 lossless palette RGB565 in firmware; downloadable lossless WebP for tablet.
72x48 PNG reference images are also retained for verification.
Logos require Pillow 12.3.0; the UI requires zopfli 0.2.3.post1 and npm ci.
Install with: python3 -m pip install Pillow==12.3.0 zopfli==0.2.3.post1
--hash-only needs only Python's standard library.
No network. Existing panel mockups are historical; the browser canvas is the
reference for the current layout. Source images retain their brand geometry.
"""
from hashlib import sha256
from io import BytesIO
import argparse
import gzip
import json
from math import ceil
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
ASSETS = ROOT / 'assets'
W, H = 24, 16
CATALOG = json.loads((ASSETS / 'airlines.json').read_text())
DEFAULT = {'code': 'DEFAULT', 'name': 'NON IDENTIFIÉ', 'aliases': [],
           'source': 'sources/DEFAULT.png'}


def build_hash(output=None):
    """Verify the vendored release, then embed its complete MIT license and JS."""
    vendor = ASSETS / 'vendor' / 'js-sha256-0.11.1'
    metadata = json.loads((vendor / 'manifest.json').read_text())
    verified = {}
    for entry in metadata['files']:
        content = (vendor / entry['file']).read_bytes()
        if len(content) != entry['bytes'] or sha256(content).hexdigest() != entry['sha256']:
            raise ValueError(f"Vendor checksum mismatch: {entry['file']}")
        verified[entry['file']] = content
    # Include the full permission notice in the firmware-distributed asset too.
    script = b'/*\n' + verified['LICENSE.txt'].rstrip() + b'\n*/\n' + verified[metadata['browser']]
    compressed_file = BytesIO()
    # GzipFile fixes mtime, filename and the platform byte, including Python 3.11.
    with gzip.GzipFile(fileobj=compressed_file, mode='wb', filename='',
                       compresslevel=9, mtime=0) as stream:
        stream.write(script)
    compressed = compressed_file.getvalue()
    lines = ['// Generated by build_assets.py --hash-only; do not edit.',
             '// js-sha256 0.11.1; provenance and SHA-256 in assets/vendor.',
             '// The served script includes its full MIT license.',
             '#pragma once', '#include <Arduino.h>', '',
             'const uint8_t FLIGHTBOARD_HASH_GZIP[] PROGMEM = {']
    for offset in range(0, len(compressed), 16):
        lines.append('  ' + ', '.join(f'0x{c:02X}' for c in compressed[offset:offset+16]) + ',')
    lines += ['};', '']
    (Path(output) if output else ROOT / 'FlightBoardHashGzip.h').write_text('\n'.join(lines))
    print(f'SHA-256 browser asset: {len(script)} bytes -> {len(compressed)} bytes gzip')


def source_image(entry):
    from PIL import Image
    data = (ASSETS / entry['source']).read_bytes()
    if entry.get('sha256') and sha256(data).hexdigest() != entry['sha256']:
        raise ValueError(f"Source checksum mismatch: {entry['code']}")
    image = Image.open(BytesIO(data)).convert('RGBA')
    # Use a documented negative brand variant only when its normal ink would
    # disappear on the black matrix. The original alpha preserves its geometry.
    if entry.get('dark_variant') == 'white':
        alpha = image.getchannel('A')
        image = Image.new('RGBA', image.size, '#ffffff')
        image.putalpha(alpha)
    # Transparent source margins differ between the catalogues.
    bbox = image.getchannel('A').getbbox()
    return image.crop(bbox) if bbox else image


def render(entry, size):
    from PIL import Image, ImageOps
    image = source_image(entry)
    margin = 1 if size == (W, H) else 4
    image = ImageOps.contain(image, (size[0] - margin * 2, size[1] - margin * 2),
                             Image.Resampling.LANCZOS)
    # PNGs retain alpha so the tablet's actual background shows through. LED
    # pixels have no alpha: transparent source pixels become unlit black.
    panel = size == (W, H)
    result = Image.new('RGBA', size, (0, 0, 0, 255 if panel else 0))
    result.alpha_composite(image, ((size[0] - image.width) // 2,
                                  (size[1] - image.height) // 2))
    return result.convert('RGB') if panel else result


def rgb565(color):
    r, g, b = color
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def pack_logo(values):
    """Lossless sorted RGB565 deltas and palette indices with compact black runs."""
    palette = sorted(set(values))
    if not palette or palette[0] != 0 or len(palette) > 254:
        raise ValueError('LED logos require black and at most 254 exact RGB565 colors')
    encoded_palette, previous = bytearray(), 0
    for color in palette:
        delta = color - previous
        previous = color
        while delta >= 128:
            encoded_palette.append((delta & 127) | 128)
            delta >>= 7
        encoded_palette.append(delta)
    palette_index = {color: i for i, color in enumerate(palette)}
    raw = [palette_index[color] for color in values]
    indices, pos = bytearray([len(palette)]), 0
    while pos < len(raw):
        count = 1
        while pos + count < len(raw) and raw[pos + count] == raw[pos] and count < 255:
            count += 1
        if raw[pos] == 0:
            # Codes above the palette encode black in one byte; 255 is reserved
            # for a repetition of any other color, followed by count and index.
            count = min(count, 255 - len(palette))
            indices.append(len(palette) + count - 1)
        elif count >= 4:
            indices.extend([255, count, raw[pos]])
        else:
            indices.extend(raw[pos:pos + count])
        pos += count
    return bytes(encoded_palette), bytes(indices)


def minify_ui(html):
    """Minify only inline JS with the pinned local tool; preserve HTML/CSS."""
    node = shutil.which('node')
    if not node:
        raise RuntimeError('UI minification requires Node.js >=18 and npm ci')
    result = subprocess.run([node, str(ROOT / 'tools/minify_web.cjs')],
                            input=html, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    if result.returncode:
        raise RuntimeError(result.stderr.decode('utf-8', errors='replace').strip())
    if not result.stdout:
        raise ValueError('UI minification produced no HTML')
    return result.stdout


def compress_ui(html):
    """Gzip the deterministic build output; keep the editable source intact."""
    try:
        import zopfli
        import zopfli.gzip
    except ImportError as error:
        raise RuntimeError('UI compression requires: python3 -m pip install zopfli==0.2.3.post1') from error
    if zopfli.__version__ != '0.2.3.post1':
        raise RuntimeError('Reproducible UI compression requires zopfli==0.2.3.post1')
    compressed = bytearray(zopfli.gzip.compress(html, numiterations=100))
    # The DEFLATE stream is platform-independent. Fix the gzip OS marker too.
    compressed[9] = 255
    compressed = bytes(compressed)
    if gzip.decompress(compressed) != html:
        raise ValueError('UI gzip did not preserve the exact minified build')
    return compressed


def build_web(html, minified, compressed):
    version = '4.1.1'
    digest = sha256(compressed).hexdigest()
    url = f'https://raw.githubusercontent.com/kmsha19/flightboard-updates/main/store/zcs-web-{version}.bin'
    if len(compressed) > 98304:
        raise ValueError('Web content exceeds the firmware upload limit')
    (ASSETS / 'zcs-web.bin').write_bytes(compressed)
    metadata = {'schema': 1, 'id': '__web', 'version': version,
                'size': len(compressed), 'sha256': digest, 'url': url,
                'sourceSha256': sha256(html).hexdigest(),
                'minifiedSha256': sha256(minified).hexdigest()}
    (ASSETS / 'zcs-web.json').write_text(json.dumps(metadata, indent=2) + '\n')
    (ROOT / 'FlightBoardWebGzip.h').write_text('\n'.join([
        '// Generated by build_assets.py. The interface is stored in the raw content bank.',
        '#pragma once', '#include <Arduino.h>', '',
        f'constexpr uint32_t ZCS_WEB_SIZE = {len(compressed)};',
        f'const char ZCS_WEB_SHA256[] PROGMEM = "{digest}";',
        f'const char ZCS_WEB_URL[] PROGMEM = "{url}";', '']))
    build_bootstrap(metadata)
    print(f'Web pack: {len(compressed)} bytes')


def build_bootstrap(metadata):
    version, digest, url = metadata['version'], metadata['sha256'], metadata['url']
    size = metadata['size']
    bootstrap = (ASSETS / 'bootstrap.html').read_text()
    for key, value in {'VERSION': version, 'SIZE': str(size),
                       'SHA256': digest, 'URL': url}.items():
        bootstrap = bootstrap.replace('__WEB_' + key + '__', value)
    if '__WEB_' in bootstrap:
        raise ValueError('Unresolved bootstrap placeholder')
    # The rescue UI has no npm dependency and stays fully available offline.
    out = BytesIO()
    with gzip.GzipFile(fileobj=out, mode='wb', filename='', compresslevel=9, mtime=0) as stream:
        stream.write(bootstrap.encode())
    small = out.getvalue()
    if len(small) > 4096:
        raise ValueError('Embedded bootstrap exceeds 4 KiB')
    lines = ['// Generated by build_assets.py from assets/bootstrap.html.',
             '#pragma once', '#include <Arduino.h>', '',
             'const uint8_t ZCS_BOOTSTRAP_GZIP[] PROGMEM = {']
    for offset in range(0, len(small), 16):
        lines.append('  ' + ', '.join(f'0x{c:02X}' for c in small[offset:offset+16]) + ',')
    lines += ['};', 'constexpr size_t ZCS_BOOTSTRAP_GZIP_SIZE = sizeof(ZCS_BOOTSTRAP_GZIP);', '']
    (ROOT / 'ZcsBootstrap.h').write_text('\n'.join(lines))
    print(f'Embedded bootstrap: {len(small)} bytes gzip')


def font(size):
    from PIL import ImageFont
    for path in ('/System/Library/Fonts/Supplemental/Arial.ttf',
                 '/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'):
        if Path(path).is_file():
            return ImageFont.truetype(path, size)
    return ImageFont.load_default(size=size)


def main(logos_only=False):
    from PIL import Image, ImageDraw
    # Validate the UI dependency before writing any generated asset.
    html = None if logos_only else re.search(r'R"FBPAGE\((.*?)\)FBPAGE"',
        (ROOT / 'FlightBoardWeb.h').read_text(), re.S).group(1).encode()
    minified = None if logos_only else minify_ui(html)
    compressed = None if logos_only else compress_ui(minified)
    if not logos_only:
        build_hash()
    (ASSETS / 'tablet').mkdir(exist_ok=True)
    lines = ['// Generated by build_assets.py — do not edit by hand.',
             '// Airline emblems from attributed sources in assets/airlines.json.',
             '#pragma once', '#include <Arduino.h>', '#include <pgmspace.h>', '',
             'constexpr uint8_t AIRLINE_LOGO_W = 24;',
             'constexpr uint8_t AIRLINE_LOGO_H = 16;', '']
    entries = CATALOG + [DEFAULT]
    images, pngs, webps, image_offsets = {}, {}, {}, {}
    image_bundle = bytearray()
    packed_bytes = 0
    for entry in entries:
        code = entry['code']
        pixels = render(entry, (W, H))
        values = [rgb565(c) for c in pixels.get_flattened_data()]
        # Show the exact RGB565 colors in the contact sheet.
        pixels.putdata([(((c >> 11) & 31) * 255 // 31,
                         ((c >> 5) & 63) * 255 // 63,
                         (c & 31) * 255 // 31) for c in values])
        images[code] = pixels
        pixels.resize((240, 160), Image.Resampling.NEAREST).save(ROOT / f'logo_{code.lower()}.png')
        tablet = render(entry, (72, 48)).quantize(colors=32, dither=Image.Dither.NONE)
        output = BytesIO()
        tablet.save(output, format='PNG', optimize=True)
        pngs[code] = output.getvalue()
        (ASSETS / 'tablet' / f'{code}.png').write_bytes(pngs[code])
        output = BytesIO()
        tablet.convert('RGBA').save(output, format='WEBP', lossless=True, method=6, quality=100, exact=True)
        webps[code] = output.getvalue()
        image_offsets[code] = len(image_bundle)
        image_bundle.extend(webps[code])
        decoded = Image.open(BytesIO(webps[code])).convert('RGBA')
        assert list(decoded.get_flattened_data()) == list(tablet.convert('RGBA').get_flattened_data())
        # Lossless per-logo palette: retain every original RGB565 pixel while
        # making room for ZCS modules in the existing OTA partition.
        palette, indices = pack_logo(values)
        packed_bytes += len(palette) + len(indices)
        lines.append(f'const uint8_t LOGO_{code}[] PROGMEM = {{')
        for offset in range(0, len(palette), 16):
            lines.append('  ' + ', '.join(f'0x{c:02X}' for c in palette[offset:offset+16]) + ',')
        lines += ['};', f'const uint8_t INDEX_{code}[] PROGMEM = {{']
        for offset in range(0, len(indices), 16):
            lines.append('  ' + ', '.join(f'0x{c:02X}' for c in indices[offset:offset+16]) + ',')
        lines += ['};', '']
    (ASSETS / 'zcs-logos.bin').write_bytes(image_bundle)
    image_digest = sha256(image_bundle).hexdigest()
    (ASSETS / 'zcs-logos.json').write_text(json.dumps({
        'schema': 1, 'id': '__logos', 'size': len(image_bundle), 'sha256': image_digest,
        'images': [{'code': entry['code'], 'offset': image_offsets[entry['code']],
                    'size': len(webps[entry['code']])} for entry in entries]
    }, ensure_ascii=False, indent=2) + '\n')
    lines += [f'constexpr uint32_t AIRLINE_IMAGES_SIZE = {len(image_bundle)};',
              f'const char AIRLINE_IMAGES_SHA256[] PROGMEM = "{image_digest}";', '']
    lines += ['struct AirlineAsset {', '  const char* code;', '  const char* name;',
              '  const char* id;', '  const uint8_t* pixels;',
              '  uint32_t imageOffset;', '  size_t imageSize;',
              '  const uint8_t* indices;', '};', '',
              'const AirlineAsset AIRLINES[] = {']
    for entry in CATALOG:
        code, name = entry['code'], entry['name']
        for alias in [code] + entry['aliases']:
            lines.append(f'  {{"{alias}", "{name}", "logo_{code.lower()}", LOGO_{code}, {image_offsets[code]}, {len(webps[code])}, INDEX_{code}}},')
    lines += ['};', 'constexpr size_t AIRLINE_COUNT = sizeof(AIRLINES) / sizeof(AIRLINES[0]);',
              f'const AirlineAsset DEFAULT_AIRLINE = {{"---", "COMPAGNIE INCONNUE", "logo_default", LOGO_DEFAULT, {image_offsets["DEFAULT"]}, {len(webps["DEFAULT"])}, INDEX_DEFAULT}};', '',
              'inline uint16_t readAirlinePixel(const AirlineAsset& airline, uint16_t index) {',
              '  if (index >= AIRLINE_LOGO_W * AIRLINE_LOGO_H) return 0;',
              '  const uint8_t* cursor = airline.indices;',
              '  const uint8_t paletteSize = pgm_read_byte(cursor++);',
              '  for (uint16_t token = 0; token < AIRLINE_LOGO_W * AIRLINE_LOGO_H; ++token) {',
              '    uint8_t colorIndex = pgm_read_byte(cursor++);',
              '    uint16_t count = 1;',
              '    if (colorIndex == 255) {',
              '      count = pgm_read_byte(cursor++); colorIndex = pgm_read_byte(cursor++);',
              '      if (!count || colorIndex >= paletteSize) return 0;',
              '    } else if (colorIndex >= paletteSize) {',
              '      count = colorIndex - paletteSize + 1; colorIndex = 0;',
              '    }',
              '    if (index >= count) { index -= count; continue; }',
              '    if (!colorIndex) return 0;',
              '    const uint8_t* delta = airline.pixels;',
              '    uint32_t color = 0;',
              '    for (uint16_t entry = 0; entry <= colorIndex; ++entry) {',
              '      for (uint8_t shift = 0; shift <= 14; shift += 7) {',
              '        const uint8_t part = pgm_read_byte(delta++);',
              '        color += uint32_t(part & 127) << shift;',
              '        if (!(part & 128)) break;',
              '        if (shift == 14) return 0;',
              '      }',
              '    }',
              '    return color <= 65535 ? uint16_t(color) : 0;',
              '  }', '  return 0;', '}', '',
              'inline const AirlineAsset* findAirline(const String& input) {',
              '  String callsign = input; callsign.trim(); callsign.toUpperCase();',
              '  if (callsign.length() < 4) return &DEFAULT_AIRLINE;',
              '  String prefix = callsign.substring(0, 3);',
              '  for (size_t i = 0; i < AIRLINE_COUNT; ++i) {',
              '    if (prefix == AIRLINES[i].code) return &AIRLINES[i];',
              '  }', '  return &DEFAULT_AIRLINE;', '}', '',
              '// The HUB75 driver supplies the callback that draws an RGB565 pixel.',
              'inline void drawAirlineLogo(int16_t x, int16_t y, const AirlineAsset& airline,',
              '                            void (*drawPixel565)(int16_t, int16_t, uint16_t)) {',
              '  for (int16_t py = 0; py < AIRLINE_LOGO_H; ++py) {',
              '    for (int16_t px = 0; px < AIRLINE_LOGO_W; ++px) {',
              '      const uint16_t c = readAirlinePixel(airline, py * AIRLINE_LOGO_W + px);',
              '      drawPixel565(x + px, y + py, c);', '    }', '  }', '}', '']
    (ROOT / 'AirlineLogos.h').write_text('\n'.join(lines))

    cols, cell_w, cell_h, heading = 4, 264, 140, 80
    sheet = Image.new('RGB', (cols * cell_w, ceil(len(CATALOG) / cols) * cell_h + heading), '#0b1418')
    draw = ImageDraw.Draw(sheet)
    draw.text((20, 15), 'FLIGHT BOARD  /  36 COMPAGNIES', font=font(24), fill='#eef7f6')
    draw.text((20, 48), 'À gauche : tablette  -  À droite : panneau LED 24 x 16', font=font(15), fill='#9ab5b3')
    for i, entry in enumerate(CATALOG):
        code = entry['code']
        x, y = i % cols * cell_w, i // cols * cell_h + heading
        draw.rounded_rectangle((x+8, y+4, x+cell_w-8, y+cell_h-4), radius=10, fill='#142126')
        tablet = Image.open(BytesIO(pngs[code])).convert('RGBA')
        tablet = tablet.resize((108, 72), Image.Resampling.LANCZOS)
        sheet.paste(tablet, (x+18, y+16), tablet)
        sheet.paste(images[code].resize((108, 72), Image.Resampling.NEAREST), (x+138, y+16))
        draw.text((x+18, y+98), f"{code}  {entry['name']}", font=font(13), fill='#eef7f6')
    sheet.save(ROOT / 'PLANCHE_LOGOS.png')
    print(f'{len(CATALOG)} airlines, {sum(1 + len(e["aliases"]) for e in CATALOG)} ICAO prefixes')
    print(f'Embedded assets: {packed_bytes} bytes lossless RGB565; downloadable WebP pack: {len(image_bundle)} bytes, SHA-256 {image_digest}')
    if logos_only:
        return
    build_web(html, minified, compressed)
    print(f'UI: {len(html)} bytes -> {len(minified)} bytes JS-minified -> {len(compressed)} bytes gzip')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    group = parser.add_mutually_exclusive_group()
    group.add_argument('--logos-only', action='store_true',
                        help='regenerate logos without updating the downloadable UI gzip')
    group.add_argument('--bootstrap-only', action='store_true',
                        help='regenerate the embedded recovery UI with the existing web manifest')
    group.add_argument('--hash-only', action='store_true',
                        help='verify and regenerate the SHA-256 browser asset without Pillow')
    args = parser.parse_args()
    if args.hash_only:
        build_hash()
    elif args.bootstrap_only:
        build_bootstrap(json.loads((ASSETS / 'zcs-web.json').read_text()))
    else:
        main(logos_only=args.logos_only)
